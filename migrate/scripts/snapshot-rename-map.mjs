// Snapshots the library's scripts/v4-rename-map.json into src/steps/data/v4-rename-map.ts,
// so the v3-to-v4 step never reads the library repo at run time.
// Run after changing ../scripts/v4-rename-map.json: node scripts/snapshot-rename-map.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const migrateDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const map = JSON.parse(fs.readFileSync(path.join(migrateDir, '..', 'scripts', 'v4-rename-map.json'), 'utf8'));
const out = path.join(migrateDir, 'src', 'steps', 'data', 'v4-rename-map.ts');

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : quote(k));
function literal(value, indent) {
    const inner = indent + '    ';
    if (value === null) return 'null';
    if (typeof value === 'string') return quote(value);
    if (Array.isArray(value)) return `[\n${value.map((v) => inner + literal(v, inner)).join(',\n')},\n${indent}]`;
    return `{\n${Object.entries(value).map(([k, v]) => `${inner}${key(k)}: ${literal(v, inner)}`).join(',\n')},\n${indent}}`;
}

fs.writeFileSync(
    out,
    `// Generated by scripts/snapshot-rename-map.mjs from scripts/v4-rename-map.json, do not edit by hand.\n` +
        `export interface V4Rename {\n` +
        `    component: string;\n` +
        `    prop: string;\n` +
        `    part: string | null;\n` +
        `    replacement: string | null;\n` +
        `    semantics: 'merge' | 'replace' | 'none';\n` +
        `    note?: string;\n` +
        `}\n\n` +
        `export const V4_RENAME_MAP: {\n` +
        `    semantics: Record<string, string>;\n` +
        `    renames: V4Rename[];\n` +
        `    classTargetChanges: { component: string; change: string }[];\n` +
        `    propRenames: { component: string; prop: string; replacement: string; note: string }[];\n` +
        `    [key: string]: unknown;\n` +
        `} = ${literal(map, '')};\n`,
);
console.log(`wrote ${map.renames.length} renames to ${path.relative(migrateDir, out)}`);
