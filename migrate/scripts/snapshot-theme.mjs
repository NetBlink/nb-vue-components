// Snapshots the @keyframes of the library's theme.css into src/steps/data/theme-keyframes.ts,
// so the v3-to-v3-2 step can drop app copies that are identical to the library's.
// Run after changing keyframes in ../theme.css: node scripts/snapshot-theme.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const migrateDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const css = fs.readFileSync(path.join(migrateDir, '..', 'theme.css'), 'utf8');
const out = path.join(migrateDir, 'src', 'steps', 'data', 'theme-keyframes.ts');

const normalize = (body) => body.replace(/\s+/g, ' ').replace(/\s*([{};:,])\s*/g, '$1').trim();

const keyframes = {};
const re = /@keyframes\s+([\w-]+)\s*\{/g;
let m;
while ((m = re.exec(css))) {
    let depth = 1;
    let i = re.lastIndex;
    while (depth && i < css.length) {
        if (css[i] === '{') depth++;
        else if (css[i] === '}') depth--;
        i++;
    }
    keyframes[m[1]] = normalize(css.slice(re.lastIndex, i - 1));
    re.lastIndex = i;
}

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lines = Object.entries(keyframes).map(([name, body]) => `    ${/^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name)}: ${quote(body)},`);
fs.writeFileSync(
    out,
    `// Generated by scripts/snapshot-theme.mjs from theme.css, do not edit by hand.\n` +
        `export const THEME_KEYFRAMES: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
console.log(`wrote ${Object.keys(keyframes).length} keyframes to ${path.relative(migrateDir, out)}`);
